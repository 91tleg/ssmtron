#!/usr/bin/env python3
"""Make firmware/lib/ui/font_b612.c: B612 Mono as 4 bit alpha bitmaps.

This is the firmware's only font. Each text size (scale) has one bitmap per
character from 0x20 to 0x5F. A cell is 6*scale wide and 7*scale tall, the
cell the layout code reserves. B612 Mono is 0.65 em wide, so the em is
6 / 0.65 = 9.23 pixels per scale step and a capital is about 7 pixels tall.

The UI asks for a few text sizes chosen for the 240 px panel (--sizes) and
scales each in proportion to the panel width, rounded, exactly as
UI_TEXT_SCALE does in ui_geom.h. A table is made for every scale any of the
supported panels (--panels) ends up with, and each one is compiled only when
the build's DISPLAY_WIDTH needs it, so a 240 px build carries the 240 px sizes
alone.

Needs Pillow:
    python3 -m venv .venv && .venv/bin/pip install -r tools/requirements.txt
Run: .venv/bin/python tools/gen_font.py
The font, tools/fonts/B612Mono-Bold.ttf, is under the SIL Open Font License,
see tools/fonts/OFL.txt.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "firmware" / "lib" / "ui" / "font_b612.c"
DEFAULT_FONT = ROOT / "tools" / "fonts" / "B612Mono-Bold.ttf"
FIRST, LAST = 0x20, 0x5F
ADVANCE_EM = 0.65  # B612 Mono: 1300 of 2000 units
CELL_W, CELL_H = 6, 7  # pixels per scale step


def ui_text_scale(n: int, width: int) -> int:
    """UI_TEXT_SCALE( n ) of ui_geom.h for a panel this wide."""
    return (n * width + 120) // 240


def render(font: ImageFont.FreeTypeFont, ch: str, scale: int) -> list[int]:
    """The character's 4 bit alpha, row by row, in a 6s by 7s cell."""
    w, h = CELL_W * scale, CELL_H * scale
    image = Image.new("L", (w, h), 0)
    ImageDraw.Draw(image).text((0, h), ch, font=font, fill=255, anchor="ls")
    if ch == "_":
        # The underscore is drawn below the baseline, outside the cell, so lift
        # it until its bottom edge is the cell's.
        tall = Image.new("L", (w, h + 2 * scale + 2), 0)
        ImageDraw.Draw(tall).text((0, h), ch, font=font, fill=255, anchor="ls")
        bottom = tall.getbbox()[3]  # one past the lowest row with ink
        lift = bottom - h
        image = Image.new("L", (w, h), 0)
        image.paste(tall.crop((0, lift, w, lift + h)), (0, 0))
    return [round(a * 15 / 255) for a in image.tobytes()]


def clipped_rows(font: ImageFont.FreeTypeFont, ch: str, scale: int) -> int:
    """How many rows of visible ink (a quarter or more) fall above the cell."""
    w, h = CELL_W * scale, CELL_H * scale
    pad = 3 * scale
    image = Image.new("L", (w, h + pad), 0)
    ImageDraw.Draw(image).text((0, h + pad), ch, font=font, fill=255, anchor="ls")
    rows = [image.crop((0, y, w, y + 1)).getextrema()[1] for y in range(pad)]
    return sum(1 for peak in rows if round(peak * 15 / 255) >= 4)


def pack(alpha: list[int]) -> list[int]:
    """Two pixels a byte, the first in the low half."""
    out = []
    for i in range(0, len(alpha), 2):
        low = alpha[i]
        high = alpha[i + 1] if i + 1 < len(alpha) else 0
        out.append(low | (high << 4))
    return out


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=DEFAULT_FONT)
    parser.add_argument("--sizes", type=int, nargs="+", default=[1, 2, 4],
                        help="the text sizes the UI uses, for the 240 px panel")
    parser.add_argument("--panels", type=int, nargs="+", default=[240, 360],
                        help="the panel widths to support")
    args = parser.parse_args()

    needed: dict[int, list[int]] = {}  # scale -> the panel widths that use it
    for width in args.panels:
        for n in args.sizes:
            needed.setdefault(ui_text_scale(n, width), [])
            if width not in needed[ui_text_scale(n, width)]:
                needed[ui_text_scale(n, width)].append(width)
    scales = sorted(needed)

    def guard(scale: int) -> str:
        terms = [f"( FONT_B612_SCALE( {n} ) == {scale} )" for n in args.sizes]
        return "#if " + " || ".join(terms)

    lines = [
        "/* clang-format off */",
        "/* Generated by tools/gen_font.py from B612 Mono. Do not edit.",
        " * B612 is under the SIL Open Font License 1.1, see tools/fonts/OFL.txt.",
        " * Each table is built only when this panel's width needs its size. */",
        "#include <stddef.h>",
        "",
        '#include "lib/display/display.h"',
        '#include "lib/ui/font_b612.h"',
        "",
        "/* UI_TEXT_SCALE of ui_geom.h, in a form the preprocessor can use. */",
        "#define FONT_B612_SCALE( n ) \\",
        "    ( ( ( ( n ) * ( DISPLAY_WIDTH ) ) + 120 ) / 240 )",
        "",
    ]
    total = 0
    clipped: list[str] = []
    # Everything sits inside the one function that reads it, so nothing else
    # in the program can see the tables.
    lines += ["const font_b612_t * font_b612_find( uint8_t scale )", "{"]
    for scale in scales:
        em = CELL_W * scale / ADVANCE_EM
        font = ImageFont.truetype(str(args.font), size=em)
        cell = CELL_W * scale * CELL_H * scale
        per = (cell + 1) // 2
        lines.append(guard(scale))
        lines.append(
            f"    static const uint8_t b612_scale{scale}"
            f"[{LAST - FIRST + 1}][{per}] = {{"
        )
        for code in range(FIRST, LAST + 1):
            alpha = render(font, chr(code), scale)
            if clipped_rows(font, chr(code), scale) > 0:
                clipped.append(f"{chr(code)}@{scale}")
            data = pack(alpha)
            body = ", ".join(f"0x{b:02x}u" for b in data)
            lines.append(f"        {{ {body} }}, /* 0x{code:02x} */")
            if scale in (1, 2, 4):
                total += len(data)
        lines.append("    };")
        lines.append("#endif")
    lines.append("    static const font_b612_t bitmaps[] = {")
    for scale in scales:
        lines.append(guard(scale))
        lines.append(
            f"        {{ {scale}u, &b612_scale{scale}[0][0], "
            f"{(CELL_W * scale * CELL_H * scale + 1) // 2}u }},"
        )
        lines.append("#endif")
    lines.append("    };")
    lines += [
        "    const font_b612_t * found = NULL;",
        "",
        "    for ( size_t i = 0; ( found == NULL ) && "
        "( i < ( sizeof( bitmaps ) / sizeof( bitmaps[0] ) ) ); i++ )",
        "    {",
        "        if ( bitmaps[i].scale == scale )",
        "        {",
        "            found = &bitmaps[i];",
        "        }",
        "    }",
        "    return found;",
        "}",
        "",
    ]
    OUTPUT.write_text("\n".join(lines))
    print(f"wrote {OUTPUT}")
    for scale in scales:
        per = (CELL_W * scale * CELL_H * scale + 1) // 2
        print(f"  scale {scale}: {per * (LAST - FIRST + 1)} bytes, "
              f"panels {needed[scale]}")
    if clipped:
        print("  ink cut off above the cell:", " ".join(clipped))


if __name__ == "__main__":
    main()
