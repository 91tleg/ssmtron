#!/usr/bin/env python3
"""Make firmware/lib/ui/logo_maxtek.[ch]: the Maxtek logo as 4 bit alpha.

The picture is dark ink on white. It is cropped to its outline and scaled to
LOGO_W pixels wide on the 240 px panel, and in proportion on the others
(--panels), rounded as UI_LEN rounds. The dial draws the alpha in black on a
light face and in white on a dark one. A table is made for every panel width
and compiled only when the build's DISPLAY_WIDTH is that one.

Needs Pillow:
    python3 -m venv .venv && .venv/bin/pip install -r tools/requirements.txt
Run: .venv/bin/python tools/gen_logo.py
"""

from __future__ import annotations

import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
UI = ROOT / "firmware" / "lib" / "ui"
DEFAULT_SOURCE = ROOT / "tools" / "logos" / "maxtek-logo-v6.png"
LOGO_W = 56  # pixels wide on the 240 px panel
ALPHA_MAX = 15


def crop_to_ink(im: Image.Image) -> Image.Image:
    box = im.point(lambda v: 255 if v < 128 else 0).getbbox()
    if box is None:
        raise SystemExit("the picture has no dark ink")
    return im.crop(box)


def size_for(src: Image.Image, panel: int) -> tuple[int, int]:
    w = (LOGO_W * panel + 120) // 240
    return w, max(1, round(w * src.height / src.width))


def alpha_rows(src: Image.Image, w: int, h: int) -> list[list[int]]:
    small = src.resize((w, h), Image.LANCZOS)
    return [
        [round((255 - small.getpixel((x, y))) * ALPHA_MAX / 255) for x in range(w)]
        for y in range(h)
    ]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--source", type=Path, default=DEFAULT_SOURCE)
    ap.add_argument("--panels", type=int, nargs="+", default=[240, 360])
    args = ap.parse_args()

    src = crop_to_ink(Image.open(args.source).convert("L"))
    sizes = {p: size_for(src, p) for p in args.panels}

    h = [
        "/* clang-format off */",
        "/* Generated by tools/gen_logo.py. Do not edit. */",
        "#ifndef LOGO_MAXTEK_H_",
        "#define LOGO_MAXTEK_H_",
        "",
        "#include <stdint.h>",
        "",
        '#include "lib/display/display.h"',
        "",
        "/* The logo's size in pixels on this panel. */",
    ]
    for i, (p, (w, hh)) in enumerate(sizes.items()):
        h.append(f"#{'if' if i == 0 else 'elif'} DISPLAY_WIDTH == {p}")
        h.append(f"#define LOGO_MAXTEK_W ( {w}u )")
        h.append(f"#define LOGO_MAXTEK_H ( {hh}u )")
    h += [
        "#else",
        "#error no logo for this DISPLAY_WIDTH, run tools/gen_logo.py",
        "#endif",
        "",
        "/* Ink at this pixel, 0 (none) to 15 (all); 0 outside the logo. */",
        "uint8_t logo_maxtek_alpha( uint16_t x, uint16_t y );",
        "",
        "#endif /* LOGO_MAXTEK_H_ */",
        "",
    ]
    (UI / "logo_maxtek.h").write_text("\n".join(h))

    c = [
        "/* clang-format off */",
        "/* Generated by tools/gen_logo.py. Do not edit. */",
        '#include "lib/ui/logo_maxtek.h"',
        "",
        "uint8_t logo_maxtek_alpha( uint16_t x, uint16_t y )",
        "{",
    ]
    for i, (p, (w, hh)) in enumerate(sizes.items()):
        c.append(f"#{'if' if i == 0 else 'elif'} DISPLAY_WIDTH == {p}")
        c.append(f"    static const uint8_t alpha[{hh}][{w}] = {{")
        for row in alpha_rows(src, w, hh):
            c.append("        { " + ", ".join(f"{v}u" for v in row) + " },")
        c.append("    };")
    c += [
        "#endif",
        "    uint8_t out = 0u;",
        "",
        "    if ( ( x < LOGO_MAXTEK_W ) && ( y < LOGO_MAXTEK_H ) )",
        "    {",
        "        out = alpha[y][x];",
        "    }",
        "    return out;",
        "}",
        "",
    ]
    (UI / "logo_maxtek.c").write_text("\n".join(c))
    for p, (w, hh) in sizes.items():
        print(f"{p} px panel: {w} x {hh}")


if __name__ == "__main__":
    main()
