/* Every parameter of every profile against the reference tool, the B10 Scan
 * Tool this firmware's profiles come from. The expected texts and bit
 * patterns were computed from that tool's own display routines, not from
 * this firmware's decoders, so a wrong scale, address or flag mask shows up
 * here. For each parameter the table gives the profile, the address, the
 * name and either what the reference shows for ten raw bytes or which flags
 * it shows as set for four raw bytes.
 *
 * Known differences from the reference, kept on purpose:
 *  - Fuel Trim: the reference cuts its magnitude toward zero. Ours cuts the
 *    signed value down, so below the midpoint it can be 0.01 more negative.
 *  - Inj Pulse Width on the 90-91 5MT and 91 Turbo: the reference shifts a
 *    16 bit register and overflows from raw 32 up, so the expected text is
 *    the value it is meant to show (raw * 2.048 ms) for every raw.
 *  - Stored Codes 3/3 on the 91-94 Turbo: the reference shows the layout
 *    without code 44 there. Ours matches the active codes byte, which has it.
 */
